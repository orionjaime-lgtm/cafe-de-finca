CREATE TABLE origen_cafe (
    id_origen INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pais VARCHAR(100) NOT NULL,
    region VARCHAR(100) NOT NULL,
    variedad VARCHAR(100),
    altura_msnm INT,
    notas_cata VARCHAR(255),
    stock_minimo_alerta_gramos NUMERIC(12,3) DEFAULT 0 CHECK (stock_minimo_alerta_gramos >= 0)
);

CREATE TABLE proveedor (
    id_proveedor INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cuit VARCHAR(20) UNIQUE NOT NULL,
    razon_social VARCHAR(150) NOT NULL,
    pais_origen VARCHAR(100),
    telefono_email VARCHAR(150)
);

CREATE TABLE lote_cafe_verde (
    id_lote_verde INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_origen INT NOT NULL REFERENCES origen_cafe (id_origen),
    id_proveedor INT NOT NULL REFERENCES proveedor (id_proveedor),
    codigo_lote VARCHAR(50) UNIQUE NOT NULL,
    fecha_ingreso DATE NOT NULL DEFAULT CURRENT_DATE,
    cant_bolsas INT NOT NULL CHECK (cant_bolsas > 0),
    peso_inicial_gramos NUMERIC(12,3) NOT NULL CHECK (peso_inicial_gramos > 0),
    stock_actual_gramos NUMERIC(12,3) NOT NULL CHECK (stock_actual_gramos >= 0)
);
CREATE INDEX idx_lote_verde_origen ON lote_cafe_verde(id_origen);
CREATE INDEX idx_lote_verde_proveedor ON lote_cafe_verde(id_proveedor);

CREATE TABLE perfil_tueste (
    id_perfil_tueste INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_perfil VARCHAR(100) NOT NULL,
    temp_objetivo_c NUMERIC(5,2) NOT NULL,
    tiempo_tueste_min INT NOT NULL CHECK (tiempo_tueste_min > 0),
    merma_esperada_pct NUMERIC(5,2),
    horas_reposo_minimas INT DEFAULT 0
);

CREATE TABLE orden_tueste (
    id_orden_tueste INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_lote_verde INT NOT NULL REFERENCES lote_cafe_verde (id_lote_verde),
    id_perfil_tueste INT NOT NULL REFERENCES perfil_tueste (id_perfil_tueste),
    fecha_hora_tueste TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    peso_verde_usado_g NUMERIC(12,3) NOT NULL CHECK (peso_verde_usado_g > 0),
    peso_tostado_obtenido_g NUMERIC(12,3) NOT NULL CHECK (peso_tostado_obtenido_g >= 0),
    merma_real_pct NUMERIC(5,2) GENERATED ALWAYS AS (
        ((peso_verde_usado_g - peso_tostado_obtenido_g) / NULLIF(peso_verde_usado_g, 0)) * 100
    ) STORED,
    operador_tostador VARCHAR(100),
    estado_orden VARCHAR(50) DEFAULT 'COMPLETADO',
    CHECK (peso_tostado_obtenido_g <= peso_verde_usado_g)
);
CREATE INDEX idx_orden_tueste_lote ON orden_tueste(id_lote_verde);
CREATE INDEX idx_orden_tueste_perfil ON orden_tueste(id_perfil_tueste);

CREATE TABLE lote_cafe_tostado (
    id_lote_tostado INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_orden_tueste INT NOT NULL UNIQUE REFERENCES orden_tueste (id_orden_tueste),
    codigo_lote_tostado VARCHAR(50) UNIQUE NOT NULL,
    fecha_hora_fin_tueste TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_disponible_venta TIMESTAMP NOT NULL,
    fecha_caducidad DATE NOT NULL,
    peso_inicial_gramos NUMERIC(12,3) NOT NULL CHECK (peso_inicial_gramos > 0),
    stock_disponible_gramos NUMERIC(12,3) NOT NULL DEFAULT 0 CHECK (stock_disponible_gramos >= 0),
    stock_reservado_gramos NUMERIC(12,3) NOT NULL DEFAULT 0 CHECK (stock_reservado_gramos >= 0),
    estado_disponibilidad VARCHAR(50) DEFAULT 'REPOSO' CHECK (estado_disponibilidad IN ('REPOSO', 'DISPONIBLE', 'AGOTADO', 'VENCIDO')),
    CHECK (stock_disponible_gramos + stock_reservado_gramos <= peso_inicial_gramos)
);

CREATE TABLE presentacion (
    id_presentacion INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_envase VARCHAR(100) NOT NULL,
    peso_gramos NUMERIC(12,3) NOT NULL CHECK (peso_gramos > 0)
);

CREATE TABLE tipo_molienda (
    id_tipo_molienda INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_molienda VARCHAR(100) NOT NULL,
    tipo_cafetera VARCHAR(100),
    nivel_granulometria VARCHAR(50),
    es_grano_entero BOOLEAN DEFAULT FALSE
);

CREATE TABLE cliente (
    id_cliente INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_cliente VARCHAR(10) NOT NULL CHECK (tipo_cliente IN ('B2B', 'B2C')),
    nombre_razon_social VARCHAR(150) NOT NULL,
    cuit_o_dni VARCHAR(20) NOT NULL,
    condicion_iva VARCHAR(50),
    plazo_cta_cte_dias INT DEFAULT 0,
    limite_credito NUMERIC(12,2) DEFAULT 0,
    contacto_wp_ig VARCHAR(100)
);

CREATE TABLE canal_venta (
    id_canal_venta INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_canal VARCHAR(100) NOT NULL,
    requiere_datos_fiscales BOOLEAN DEFAULT FALSE,
    permite_cta_cte BOOLEAN DEFAULT FALSE
);

CREATE TABLE suscripcion (
    id_suscripcion INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente INT NOT NULL REFERENCES cliente (id_cliente),
    frecuencia VARCHAR(20) NOT NULL CHECK (frecuencia IN ('SEMANAL', 'MENSUAL')),
    proxima_fecha_generacion DATE NOT NULL,
    estado VARCHAR(20) DEFAULT 'ACTIVA' CHECK (estado IN ('ACTIVA', 'PAUSADA', 'CANCELADA'))
);
CREATE INDEX idx_suscripcion_cliente ON suscripcion(id_cliente);

CREATE TABLE detalle_suscripcion (
    id_detalle_suscripcion INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_suscripcion INT NOT NULL REFERENCES suscripcion (id_suscripcion),
    id_presentacion INT NOT NULL REFERENCES presentacion (id_presentacion),
    id_tipo_molienda INT NOT NULL REFERENCES tipo_molienda (id_tipo_molienda),
    cantidad_envases INT NOT NULL CHECK (cantidad_envases > 0)
);
CREATE INDEX idx_det_susc_suscripcion ON detalle_suscripcion(id_suscripcion);
CREATE INDEX idx_det_susc_presentacion ON detalle_suscripcion(id_presentacion);
CREATE INDEX idx_det_susc_molienda ON detalle_suscripcion(id_tipo_molienda);

CREATE TABLE hoja_ruta (
    id_hoja_ruta INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_reparto DATE NOT NULL,
    estado_ruta VARCHAR(50) DEFAULT 'PENDIENTE' CHECK (estado_ruta IN ('PENDIENTE', 'EN_CURSO', 'COMPLETADA', 'CANCELADA'))
);

CREATE TABLE pedido (
    id_pedido INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente INT NOT NULL REFERENCES cliente (id_cliente),
    id_canal_venta INT NOT NULL REFERENCES canal_venta (id_canal_venta),
    id_suscripcion INT REFERENCES suscripcion (id_suscripcion),
    id_hoja_ruta INT REFERENCES hoja_ruta (id_hoja_ruta),
    fecha_hora_pedido TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_entrega_prevista DATE,
    estado_preparacion VARCHAR(50) DEFAULT 'PENDIENTE' CHECK (estado_preparacion IN ('PENDIENTE', 'EN_PREPARACION', 'LISTO', 'ENTREGADO', 'CANCELADO')),
    estado_cobro VARCHAR(50) DEFAULT 'PENDIENTE' CHECK (estado_cobro IN ('PENDIENTE', 'PARCIAL', 'PAGADO', 'REEMBOLSADO')),
    monto_total NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (monto_total >= 0)
);
CREATE INDEX idx_pedido_cliente ON pedido(id_cliente);
CREATE INDEX idx_pedido_canal ON pedido(id_canal_venta);
CREATE INDEX idx_pedido_suscripcion ON pedido(id_suscripcion);
CREATE INDEX idx_pedido_hojaruta ON pedido(id_hoja_ruta);

CREATE TABLE detalle_pedido (
    id_detalle_pedido INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pedido INT NOT NULL REFERENCES pedido (id_pedido),
    id_lote_tostado INT NOT NULL REFERENCES lote_cafe_tostado (id_lote_tostado),
    id_presentacion INT NOT NULL REFERENCES presentacion (id_presentacion),
    id_tipo_molienda INT NOT NULL REFERENCES tipo_molienda (id_tipo_molienda),
    cantidad_envases INT NOT NULL CHECK (cantidad_envases > 0),
    peso_total_gramos NUMERIC(12,3) NOT NULL CHECK (peso_total_gramos > 0),
    precio_unitario NUMERIC(12,2) NOT NULL CHECK (precio_unitario >= 0),
    subtotal NUMERIC(12,2) NOT NULL CHECK (subtotal >= 0),
    CHECK (subtotal = cantidad_envases * precio_unitario)
);
CREATE INDEX idx_det_pedido_pedido ON detalle_pedido(id_pedido);
CREATE INDEX idx_det_pedido_lote ON detalle_pedido(id_lote_tostado);
CREATE INDEX idx_det_pedido_presentacion ON detalle_pedido(id_presentacion);
CREATE INDEX idx_det_pedido_molienda ON detalle_pedido(id_tipo_molienda);

CREATE TABLE factura (
    id_factura INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pedido INT NOT NULL UNIQUE REFERENCES pedido (id_pedido),
    tipo_comprobante VARCHAR(20) NOT NULL,
    fecha_emision DATE NOT NULL DEFAULT CURRENT_DATE,
    fecha_vencimiento DATE,
    monto_total NUMERIC(12,2) NOT NULL CHECK (monto_total >= 0)
);

CREATE TABLE medio_pago (
    id_medio_pago INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_medio VARCHAR(50) NOT NULL,
    requiere_comprobante BOOLEAN DEFAULT FALSE
);

CREATE TABLE pago (
    id_pago INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pedido INT NOT NULL REFERENCES pedido (id_pedido),
    id_medio_pago INT NOT NULL REFERENCES medio_pago (id_medio_pago),
    fecha_hora_pago TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    monto_pagado NUMERIC(12,2) NOT NULL CHECK (monto_pagado > 0)
);
CREATE INDEX idx_pago_pedido ON pago(id_pedido);
CREATE INDEX idx_pago_medio ON pago(id_medio_pago);

-- Comentarios documentales
COMMENT ON COLUMN origen_cafe.stock_minimo_alerta_gramos IS 'Alerta predictiva para evitar quiebre de stock';
COMMENT ON COLUMN lote_cafe_tostado.id_orden_tueste IS 'Relación 1 a 1 asegurada por UNIQUE';
COMMENT ON COLUMN lote_cafe_tostado.fecha_caducidad IS 'Control de frescura exigido por la cátedra';
COMMENT ON COLUMN lote_cafe_tostado.stock_reservado_gramos IS 'Para congelar gramos al tomar pedidos';
COMMENT ON COLUMN presentacion.peso_gramos IS 'Clave para convertir automáticamente todo a gramos';
COMMENT ON COLUMN cliente.tipo_cliente IS 'B2B (Corporativo) o B2C (Consumidor Final)';
COMMENT ON COLUMN suscripcion.frecuencia IS 'SEMANAL o MENSUAL';
COMMENT ON COLUMN pedido.id_suscripcion IS 'Solo si es generado automáticamente';
COMMENT ON COLUMN pedido.id_hoja_ruta IS 'Para agrupar pedidos en el reparto';
COMMENT ON COLUMN factura.id_pedido IS 'Relación 1 a 0..1 (Solo se emite en B2B)';
COMMENT ON COLUMN pago.id_pedido IS 'Múltiples pagos posibles para un mismo pedido';